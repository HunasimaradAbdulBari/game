// pages/api/generate-question.js - OpenAI Chat Completions API
export default async function handler(req, res) {
  // Only allow POST requests
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  const { subject, level } = req.body;

  // Validate input parameters
  if (!subject || !level) {
    return res.status(400).json({ error: 'Subject and level are required' });
  }

  // Validate subject
  const validSubjects = ['physics', 'chemistry', 'electronics'];
  if (!validSubjects.includes(subject.toLowerCase())) {
    return res.status(400).json({ error: 'Invalid subject' });
  }

  // Validate level
  const numLevel = parseInt(level);
  if (numLevel < 1 || numLevel > 3) {
    return res.status(400).json({ error: 'Level must be 1, 2, or 3' });
  }

  try {
    // Check for OpenAI API key
    const apiKey = process.env.OPENAI_API_KEY;
    if (!apiKey) {
      console.error('OpenAI API key not found in environment variables');
      return res.status(500).json({ error: 'API configuration error - missing API key' });
    }

    // Define difficulty levels
    const difficultyMap = {
      1: 'beginner',
      2: 'intermediate', 
      3: 'advanced'
    };

    const difficulty = difficultyMap[numLevel];

    // Create subject-specific prompts
    const subjectPrompts = {
      physics: {
        1: "Generate a simple physics experiment question about basic mechanics, motion, or forces. The experiment should use common lab equipment like pendulums, springs, or measuring tools.",
        2: "Generate an intermediate physics experiment question about electricity, magnetism, or wave properties. Include equipment like resistors, voltmeters, oscilloscopes.",
        3: "Generate an advanced physics experiment question about complex phenomena like material properties, advanced circuits, or precision measurements."
      },
      chemistry: {
        1: "Generate a basic chemistry experiment question about acid-base reactions, simple titrations, or solution preparation using common lab glassware.",
        2: "Generate an intermediate chemistry experiment question about crystallization, separation techniques, or quantitative analysis.",
        3: "Generate an advanced chemistry experiment question about organic synthesis, complex reactions, or instrumental analysis."
      },
      electronics: {
        1: "Generate a simple electronics experiment question about basic circuits, LED operation, or component identification using breadboards and basic components.",
        2: "Generate an intermediate electronics experiment question about amplifiers, signal processing, or circuit analysis using oscilloscopes and function generators.",
        3: "Generate an advanced electronics experiment question about digital logic, complex circuits, or microprocessor applications."
      }
    };

    const prompt = `${subjectPrompts[subject.toLowerCase()][numLevel]}

Requirements:
- Keep the question concise and clear (1-2 sentences max)
- Focus on practical lab work that students can perform
- Make it appropriate for ${difficulty} level students
- The question should sound like a teacher giving an assignment
- Start with phrases like "I need you to..." or "Help me gather equipment for..." or "Set up an experiment to..."

Return ONLY the experiment question, nothing else.`;

    console.log('Making OpenAI API call...');

    // Call OpenAI Chat Completions API (Updated format)
    const response = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model: 'gpt-3.5-turbo', // Using reliable model
        messages: [
          {
            role: 'system',
            content: 'You are a science teacher creating experiment questions for students. Generate clear, practical experiment questions that require specific lab equipment.'
          },
          {
            role: 'user',
            content: prompt
          }
        ],
        max_tokens: 100,
        temperature: 0.7,
      }),
    });

    console.log(`OpenAI API Response Status: ${response.status}`);

    if (!response.ok) {
      const errorText = await response.text();
      console.error('OpenAI API Error:', response.status, errorText);
      return res.status(500).json({ 
        error: 'Failed to generate question from AI service',
        details: `HTTP ${response.status}: ${errorText}`
      });
    }

    const data = await response.json();
    console.log('OpenAI API Response:', data);

    const generatedQuestion = data.choices[0]?.message?.content?.trim();

    if (!generatedQuestion) {
      console.error('No question generated by AI');
      return res.status(500).json({ error: 'No question generated by AI' });
    }

    // Return the generated question
    return res.status(200).json({
      success: true,
      question: generatedQuestion,
      subject: subject,
      level: numLevel,
      difficulty: difficulty,
      timestamp: new Date().toISOString()
    });

  } catch (error) {
    console.error('API Handler Error:', error);
    return res.status(500).json({ 
      error: 'Internal server error',
      details: process.env.NODE_ENV === 'development' ? error.message : 'Something went wrong'
    });
  }
}
